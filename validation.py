"""Pydantic v2 models for every inter-stage message + validation helper.

**Rule of the system:** all IPC between orchestrators, agents and the
integration layer is structured JSON that must pass through
:func:`validate_or_error`.  On failure the next stage receives a *concise
structured error* such as ``{"error": "Missing field: target_files"}`` --
never a raw traceback.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional, Tuple

from pydantic import (BaseModel, ConfigDict, Field, ValidationError)

# ---------------------------------------------------------------------------
# Models
# ---------------------------------------------------------------------------
_TASK_STATUSES = {"pending", "in_progress", "done", "failed", "blocked"}


class MetricSpec(BaseModel):
    """Objective gate definition (v2.6): an experiment/benchmark contract.

    When a task carries a ``MetricSpec``, the real-execution gate runs the
    task's ``run_command`` and validates the JSON it writes to
    ``results_path`` instead of gating on pytest pass-count growth.  This
    is the generic objective gate used by ML experiments *and* code
    benchmark tasks.
    """

    name: str = "primary"
    direction: str = "maximize"          # maximize | minimize
    target: Optional[float] = None
    min_improvement: float = 0.0         # vs ``baseline``
    baseline: Optional[float] = None
    #: Required ``split_hash`` value in the metrics JSON.  Candidates must
    #: agree on the split for their scores to be comparable at all.
    split_key: Optional[str] = None
    required_fields: List[str] = Field(default_factory=list)


class ObjectiveGateResult(BaseModel):
    """Machine-readable outcome of one objective-gate run (v2.6)."""

    task_id: str = ""
    passed: bool = False
    metrics: Dict[str, Any] = Field(default_factory=dict)
    primary: Optional[float] = None
    baseline: Optional[float] = None
    improvement: Optional[float] = None
    reason: str = ""
    runtime_s: float = 0.0
    split_hash: Optional[str] = None


class StrategySpec(BaseModel):
    """One divergence candidate approach (v2.6).

    ``approach`` is the strategy brief injected into the Builder prompt;
    ``model_role`` optionally pins the routing role for that candidate so
    different candidates can be generated by different models.
    """

    name: str = Field(min_length=1)
    approach: str = ""
    model_role: Optional[str] = None
    seed: Optional[int] = None
    params: Dict[str, Any] = Field(default_factory=dict)


class TaskSpec(BaseModel):
    """A unit of work on a project task board."""

    model_config = ConfigDict(extra="ignore")

    id: str = Field(min_length=1)
    title: str
    objective: str
    # Required on purpose: validation failures produce
    # {"error": "Missing field: target_files"}.
    target_files: List[str]
    #: v2.8: permit rewriting pre-existing tests / pytest config.  Off by
    #: default -- those files are the fixed specification this task is graded
    #: against.  Only the rare bootstrap task (the one that *creates* the test
    #: harness) should set it.
    allow_test_edits: bool = False
    dependencies: List[str] = Field(default_factory=list)
    priority: str = "medium"          # high | medium | low
    acceptance_criteria: List[str] = Field(default_factory=list)
    workspace_patterns_referenced: List[str] = Field(default_factory=list)
    retry_count: int = 0
    status: str = "pending"
    last_feedback: Optional[str] = None
    error_signature: Optional[str] = None
    task_type: str = "feature"        # feature | bugfix
    should_pass: bool = True          # demo-mode simulation switch
    #: Tests-first workflow: the real gate demands the task's own tests
    #: actually RUN (final passed count must exceed the pre-task baseline).
    requires_new_tests: bool = False
    #: 2026-10-17: the test path of record for an authored (tests-first)
    #: task.  Test files whose names do not follow the ``test_<module>.py``
    #: convention were otherwise undiscoverable by the critic: a task whose
    #: authored test lives at a disambiguated path was graded from files
    #: that never existed, so the scheduler blocked it forever.  None for
    #: boards authored before this field or tasks without their own file.
    authored_test_path: Optional[str] = None
    completed_at: Optional[str] = None
    #: v2.5.5: automatic requeues already consumed by the bounded
    #: auto-requeue policy (see ``config.FAILED_AUTO_REQUEUES``).
    auto_requeues: int = 0
    #: v2.5.5: ISO timestamp written when the task escalates; feeds the
    #: auto-requeue cooldown.
    failed_at: Optional[str] = None
    #: v2.6: ISO timestamp until which a quota-deferred task is skipped.
    #: Set when free LLM capacity is exhausted; cleared on manual retry or
    #: the next successful scheduling attempt.
    defer_until: Optional[str] = None
    #: v2.6 objective gate: when ``metric`` is set, the real-execution gate
    #: runs ``run_command`` and validates ``results_path`` JSON instead of
    #: gating on pytest.  Used by ML experiments and benchmark tasks.
    metric: Optional[MetricSpec] = None
    run_command: Optional[str] = None
    results_path: str = "reports/metrics.json"
    max_runtime_s: Optional[int] = None
    #: v2.6 divergence: multiple candidate approaches for one task.  When
    #: empty and the project/task does not opt in, today's single-candidate
    #: behaviour is preserved exactly.
    strategies: List[StrategySpec] = Field(default_factory=list)
    divergent: Optional[bool] = None
    n_candidates: int = 0

    def keywords(self) -> str:
        """Best text used to query pattern / anti-pattern memory."""
        return self.error_signature or f"{self.title} {self.objective}"


