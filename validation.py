# ---------------------------------------------------------------------------
# Validation helper -- THE single gateway for cross-stage messages
# ---------------------------------------------------------------------------
def validate_or_error(model_cls: type, data: Any) -> Tuple[Any, Optional[Dict[str, str]]]:
    """Validate *data* against *model_cls*.

    Returns ``(instance, None)`` on success, or ``(None, {"error": "..."})``
    with a concise message on failure.  Missing required fields are reported
    exactly like ``{"error": "Missing field: target_files"}``.
    """
    try:
        return model_cls.model_validate(data), None
    except ValidationError as exc:
        return None, {"error": _concise_message(exc)}


def _concise_message(exc: ValidationError) -> str:
    """Build a short, structured error message from a Pydantic error."""
    errors = exc.errors()
    for err in errors:  # missing required fields get top billing
        if err.get("type") == "missing":
            loc = ".".join(str(part) for part in err.get("loc", ()) )
            return f"Missing field: {loc}" if loc else "Missing field"
    parts = []
    for err in errors[:3]:
        loc = ".".join(str(part) for part in err.get("loc", ()))
        msg = err.get("msg", "invalid value")
        parts.append(f"{loc}: {msg}" if loc else msg)
    more = f" (+{len(errors) - 3} more)" if len(errors) > 3 else ""
    return f"Invalid payload: {'; '.join(parts)}{more}"
