class CycleSummary(BaseModel):
    """Compact per-task cycle summary written to ``cycle_summary.json``."""

    task_id: str
    attempts: int = Field(ge=1)
    verdict: str = Field(min_length=1)  # APPROVED | CHANGES_REQUESTED | ESCALATED | CRASHED
    model_used: str
    duration_s: float = Field(ge=0)
    escalated: bool = False
    reason: Optional[str] = None
    files_applied: int = 0  # real-execution mode: files actually patched


class PatchFailure(BaseModel):
    """One file that could not be patched, with a concise reason."""

    file: str
    reason: str


class PatchResult(BaseModel):
    """Outcome of applying a Builder diff to the project tree."""

    applied: List[str] = Field(default_factory=list)
    failed: List[PatchFailure] = Field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.failed


class IntegrationEvent(BaseModel):
    """Notification emitted by a ProjectOrchestrator after a completed task.

    ``modules_touched`` (optional, additive) lists module basenames of the
    changed files *plus* modules imported inside the diff -- this is what the
    IntegrationAgent's conflict heuristic scans for.
    """

    source_project: str
    task_id: str
    files_changed: List[str] = Field(default_factory=list)
    status: str = "completed"
    modules_touched: List[str] = Field(default_factory=list)


# ---------------------------------------------------------------------------
# Board write authority (v2.8, retained across the v2.9 Council removal)
#
# The authority boundary is enforced *structurally*, not by convention: any
# component that wants to change a task proposes a named action, and the
# harness will execute it only if the action maps to board keys listed here.
# No such action can reach a verdict, a pytest result, a metric value, or
# applied code -- those belong to deterministic harness gates, and letting an
# LLM reach them would reintroduce the exact weakness v2.8 exists to remove.
#
# v2.9 deleted the Council, the only consumer of this map.  It is kept because
# escalation diagnosis now auto-applies two of these same remedies
# (``narrow_objective``, ``split_task``) from a model that also produced the
# failing task, so the same whitelist is what stops a bad diagnosis from
# rewriting a board arbitrarily.
# ---------------------------------------------------------------------------

#: Board keys any automated remedy may touch, keyed by remedy name.  Anything
#: outside this map is not executable.
BOARD_WRITE_ALLOWLIST = {
    "requeue_task": ("status", "retry_count", "last_feedback", "auto_requeues",
                     "failed_at"),
    "narrow_objective": ("objective", "acceptance_criteria", "title"),
    "redesign_task": ("objective", "acceptance_criteria", "title"),
    "split_task": ("status",),
    "defer_task": ("status", "defer_until"),
    "deprioritize_task": ("priority",),
}


def board_keys_for(remedy: str) -> tuple:
    """Board keys *remedy* is permitted to write. Empty = not executable."""
    return BOARD_WRITE_ALLOWLIST.get(str(remedy or ""), ())


def is_executable_remedy(remedy: str) -> bool:
    """True when *remedy* is allowed to mutate the board at all."""
    return str(remedy or "") in BOARD_WRITE_ALLOWLIST


